-- ══════════════════════════════════════════════════════════════════════════════
--  Tabla qr_pago — QR de cobro digital (Yape / Plin) separados por tipo
--  Un QR para MEMBRESÍAS y otro para VENTAS, cada uno activable/desactivable.
--  Ejecutar una sola vez sobre la base de datos (canobd).
-- ══════════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS public.qr_pago (
    id_qr          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo           character varying(20) NOT NULL UNIQUE,   -- 'membresia' | 'venta'
    imagen         text,                                    -- data URL base64 del QR
    activo         boolean NOT NULL DEFAULT true,
    descripcion    character varying(120),
    modificado_por integer,
    created_at     timestamp with time zone DEFAULT now() NOT NULL,
    updated_at     timestamp with time zone DEFAULT now() NOT NULL
);

-- Filas base: una por cada tipo de cobro
INSERT INTO public.qr_pago (tipo, descripcion, activo)
VALUES
    ('membresia', 'QR para el cobro de membresías (Yape / Plin)', true),
    ('venta',     'QR para el cobro de ventas (Yape / Plin)',     true)
ON CONFLICT (tipo) DO NOTHING;

-- Migrar el QR único anterior (configuracion_imagenes.qr_pago_base64) al de membresía,
-- solo si el nuevo aún no tiene imagen.
UPDATE public.qr_pago q
SET imagen = c.valor
FROM public.configuracion_imagenes c
WHERE c.clave = 'qr_pago_base64'
  AND q.tipo  = 'membresia'
  AND q.imagen IS NULL;
